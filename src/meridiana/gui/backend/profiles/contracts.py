"""Presentation fragments supplied at existing schema composition points."""
from typing import Protocol

class GuiProfile(Protocol):
    id: str
    revision: int
    def append_fields(self, section: str, schema, project, obj, session) -> None: ...
    def append_chart_fields(self, kind: str, editor) -> None: ...
    def bill_columns(self, project) -> tuple[str, ...]: ...
    def activity_note(self, fire) -> str: ...
