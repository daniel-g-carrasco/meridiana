"""Project-scoped regulatory services; implementations hold no project state."""

from __future__ import annotations

from typing import TYPE_CHECKING, Protocol
from datetime import date

if TYPE_CHECKING:
    import numpy as np
    import pandas as pd
    from meridiana.core.energy.consumption import Context, Guess, Consumption
    from meridiana.core.model.model import Project, SubField, Network
    from meridiana.core.energy.components import InverterSpec
    from meridiana.core.energy.optimizers import Optimizer, FixedVoltage, Rules
    from meridiana.core.rules.rules import Facts, Rule
    from meridiana.core.rules.checks import Item
    from meridiana.core.rules.vvf_activities import Activity
    from meridiana.core.rules.types import StandardRef, FirePolicy, InputField


class CalendarPolicy(Protocol):
    codes: tuple[str, ...]
    default_timezone: str
    source: str

    def holidays(self, year: int) -> set[date]: ...
    def band_of(self, index: pd.DatetimeIndex, timezone: str) -> np.ndarray: ...


class ConsumptionPolicy(Protocol):
    def guess(self, ctx: Context) -> Guess: ...
    def valid_supply_id(self, value: str) -> bool: ...
    def shape(self, profile: str, index: pd.DatetimeIndex) -> pd.Series: ...
    def profiles(self) -> dict: ...
    def names(self) -> dict[str, str]: ...
    def starting_kwh(self) -> dict[str, float]: ...
    def prepare(self, consumption: Consumption) -> Consumption: ...
    def has_data(self, consumption: Consumption) -> bool: ...
    def follows_production(self, consumption: Consumption, ctx: Context) -> bool: ...
    def text(self, key: str) -> str: ...


class EconomyPolicy(Protocol):
    regimes: tuple[str, ...]

    def prices(self, settings) -> dict[str, float]: ...
    def zone_from_address(self, address: str) -> str: ...
    def tip(self, pz_eur_mwh, power_kw: float, zone: str, grant_pct: float = 0.0): ...
    def flows(self, settings, self_by_band, export_y, p_stc_kw: float, address: str, capex: float): ...
    def community_steps(self, settings, year1: dict, zone: str, tariff: float) -> list: ...
    def pedigree(self, key: str): ...
    def text(self, key: str) -> str: ...


class ElectricalPolicy(Protocol):
    voc_fallback: float | None
    voltage_fallback: float | None
    ki_default: float | None
    allow_auto: bool
    source: str

    def parallel_cap(self, module, ki: float) -> int | None: ...
    def selv(self, uoc_max: float) -> list: ...
    def protection(self, parallel: int, isc_max: float, ocpr: float | None, input_index: int) -> list: ...
    def pedigree(self, key: str): ...
    def text(self, key: str) -> str: ...


class RegulatoryProfile(Protocol):
    id: str
    revision: int
    def standards(self) -> tuple[StandardRef, ...]: ...
    def facts(self, project: Project, results: dict | None = None,
              energy: dict | None = None, inverter: InverterSpec | None = None) -> Facts: ...
    def rules(self) -> tuple[Rule, ...]: ...
    def title(self, rule: Rule, facts: Facts) -> str: ...
    def in_document(self, rule: Rule, facts: Facts) -> bool: ...
    def chapter_names(self) -> dict[int, str]: ...
    def design(self, facts: Facts) -> str: ...
    def minimum(self, facts: Facts) -> tuple[float, float] | None: ...
    def auto_level(self, power_kw: float) -> str: ...
    def region_of(self, address: str) -> str: ...
    def technical_rule(self, network: Network) -> str: ...
    def connection(self, p_kw: float, phases: int | None, chosen: bool,
                   level: str = "BT", auto: bool = True) -> list[Item]: ...
    def rule_items(self, facts: Facts) -> list[Item]: ...
    def fire(self, project: Project, sf: SubField | None = None) -> FirePolicy: ...
    def fire_group_items(self, placed, params, frame, size, result, subfield, target, fix, label,
                         name: str = "") -> list[Item]:
        """Insert the policy's manual-layout checks at their original point in the sequence (`name`: the
        sub-field's name as the checks show it)."""
        ...
    def layout_note(self, name: str, sfid: str, note: str) -> Item | None: ...
    def activity(self, number: int) -> Activity | None: ...
    def activities(self, query: str = "") -> list[Activity]: ...
    def validate_inputs(self, raw: dict) -> None: ...
    def validate_fire(self, raw: dict, path: str) -> None:
        """Building-level hook to preserve the structural validator's error order."""
        ...
    def fields(self, section: str) -> tuple[InputField, ...]: ...
    def defaults(self, section: str) -> dict: ...
    def electrical(self) -> ElectricalPolicy: ...
    def market_rules(self, opt: Optimizer, inv: FixedVoltage,
                     base: Rules | None, reason: str) -> tuple[Rules | None, str]: ...
    def optimizer_parallel(self, family_id: str, declared: dict) -> dict | None: ...
    def partial_fixed_check(self, string):
        """A market-specific check at the existing partial-optimizer check position."""
        ...
    def calendar(self) -> CalendarPolicy: ...
    def consumption(self) -> ConsumptionPolicy: ...
    def economics(self) -> EconomyPolicy: ...
    def text(self, key: str) -> str: ...
