"""Map selection and scene records without Qt. Coordinates are metres East, minus North."""

from __future__ import annotations

import math
import time
from functools import lru_cache

from ... import geo, tiles, view_colours, worldmap
from ...i18n import _

FAR_MPP, NEAR_MPP = 2000.0, 1500.0
FAILOVER_THRESHOLD, FAILOVER_COOLDOWN = 3, 180.0
# R540, never a bare band: under the view's tiles lies a backdrop two zooms coarser over three times the view (a view
# more on every side, about half the tiles of the view itself), and a tile still on its way is stood in for by the
# nearest coarser one already in memory, enlarged, as every web map does.
BACKDROP_STEPS, BACKDROP_REACH = 2, 1.0
# R539: past a source's coarsest level (the national orthophoto has none past 1:500.000) its nearest level is drawn
# around the site, at most this many tiles, and the street map under the whole view where the photo does not reach
FAR_PHOTO_TILES = 64
ANCESTOR_STEPS = 6


def quad_matrix(quad):
    """Row-major 4x4 homography from the unit square to a clockwise scene quad."""
    (x0, y0), (x1, y1), (x2, y2), (x3, y3) = quad
    dx1, dx2, dx3 = x1 - x2, x3 - x2, x0 - x1 + x2 - x3
    dy1, dy2, dy3 = y1 - y2, y3 - y2, y0 - y1 + y2 - y3
    det = dx1 * dy2 - dx2 * dy1
    g = (dx3 * dy2 - dx2 * dy3) / det if abs(det) > 1e-20 else 0
    h = (dx1 * dy3 - dx3 * dy1) / det if abs(det) > 1e-20 else 0
    return [x1 - x0 + g * x1, x3 - x0 + h * x3, 0, x0,
            y1 - y0 + g * y1, y3 - y0 + h * y3, 0, y0,
            0, 0, 1, 0, g, h, 0, 1]


def underlay_record(item):
    return dict(id=item.id, source='data:image/png;base64,' + item.image,
                matrix=quad_matrix([(x, -y) for x, y in item.corners()]),
                opacity=min(1, max(0, item.opacity)), visible=item.visible,
                width=item.width, height=item.height)


@lru_cache(maxsize=4096)
def _tile_records(origin, tile, url):
    key, z, x, y = tile
    return tuple(dict(source=url, clip=[u0 * 256, v0 * 256, (u1 - u0) * 256, (v1 - v0) * 256],
                      matrix=quad_matrix([(east, -north) for east, north in quad]), key=key, zoom=z)
                 for u0, v0, u1, v1, quad in tiles.tile_mesh(origin, z, x, y))


def tile_records(origin, tile, url):
    """The parts of a tile on the plan, kept once computed (R498): the mesh of a tile in local metres does not change
    with the view, and every tile that arrives during a zoom refreshed the records of all the tiles on show."""
    return list(_tile_records(origin, tile, url))


def _path(points, close=True):
    if len(points) < (3 if close else 2):
        return ''
    # Qt's path triangulator loses the fill at continental coordinates in metres.
    # Kilometres keep its internal fixed-point arithmetic in range; QML restores the scale.
    return 'M' + ' L'.join(f'{x / 1000:.5f},{y / 1000:.5f}' for x, y in points) + (' Z' if close else '')


@lru_cache(maxsize=8)
def world_geometry(origin, equal_earth):
    """Natural Earth geometry, cached per site and projection, never regenerated by a pan."""
    def point(lon, lat):
        x, y = (worldmap.equal_earth(lon, lat, origin.lon, origin.lat) if equal_earth
                else origin.to_local(lon, lat))
        return x, -y

    def segments(ring, close=True):
        out, current, previous = [], [], None
        for lon, lat in ring:
            relative = (lon - origin.lon + 180) % 360 - 180
            if equal_earth and previous is not None and abs(relative - previous) > 180:
                out.append(_path(current, close))
                current = []
            if equal_earth or tiles.angular_distance(origin, lon, lat) <= tiles.HEMISPHERE_DEGREES:
                current.append(point(lon, lat))
            elif not close:
                out.append(_path(current, False))
                current = []
            previous = relative
        out.append(_path(current, close))
        return ' '.join(p for p in out if p)

    countries, labels = [], []
    for index, country in enumerate(worldmap.countries()):
        if not equal_earth and tiles.angular_distance(origin, *country.label) > 100:
            continue
        path = ' '.join(segments(ring) for polygon in country.polygons for ring in polygon)
        countries.append(dict(name=country.name, path=path,
                              colour=view_colours.WORLD['land'][index % 3]))
        if country.label_rank <= 6 and (equal_earth or tiles.angular_distance(origin, *country.label) <= 80):
            x, y = point(*country.label)
            labels.append(dict(name=country.italian_name, x=x, y=y, rank=country.label_rank))
    lines = [segments([(lon, lat) for lat in range(-80, 81, 2)], False) for lon in range(-180, 181, 30)]
    lines += [segments([(lon, lat) for lon in range(-180, 181, 2)], False) for lat in range(-60, 61, 30)]
    return dict(countries=countries, labels=sorted(labels, key=lambda label: label['rank']),
                graticule=' '.join(lines), ocean=view_colours.WORLD['ocean'],
                border=view_colours.WORLD['border'], label=view_colours.WORLD['label'])


class PlanMaps:
    """The designer's choice stays separate from the available source and its transient failures."""

    def __init__(self, origin=None, *, custom_sources=(), sources=None):
        self.origin = origin or geo.Origin(45.4642, 9.19)
        self.sources = dict(sources) if sources is not None else tiles.catalogue(custom_sources)
        self.choice, self.source = tiles.AUTO, tiles.NONE
        self.equal_earth = False
        self.mpp, self.dpr = 1.0, 1.0
        self.bounds = (-60, -60, 60, 60)
        self.veil = view_colours.VEIL
        self.wanted, self.failures = set(), set()
        self.around = set()             # fetched in advance: the ring around the view and the zoom above (R466)
        self.backdrop, self.under = set(), {}   # the coarse tiles under the view, and those of them loaded (R540)
        self.memory = None              # tile -> its image's address when the memory holds it (MapController), R540
        self.loaded, self.unavailable = {}, {}
        self.fallback_from = ''
        self.choose()

    def set_catalogue(self, custom_sources):
        self.sources = tiles.catalogue(custom_sources)
        self.loaded.clear()
        self.unavailable.clear()
        self.choose()

    def set_source(self, choice):
        self.choice = choice
        self.fallback_from = ''
        self.choose()

    def set_view(self, bounds, mpp, dpr=1):
        if not math.isfinite(mpp) or mpp <= 0 or not math.isfinite(dpr) or dpr <= 0:
            raise ValueError('map scale and device pixel ratio must be positive and finite')
        if len(bounds) != 4 or not all(math.isfinite(v) for v in bounds):
            raise ValueError('finite view bounds are required')
        self.bounds, self.mpp, self.dpr = tuple(bounds), mpp, dpr
        self.equal_earth = mpp >= (NEAR_MPP if self.equal_earth else FAR_MPP)
        self.choose()

    def choose(self, now=None):
        now = time.monotonic() if now is None else now
        self.unavailable = {key: at for key, at in self.unavailable.items() if now - at < FAILOVER_COOLDOWN}
        key = tiles.effective(self.choice, self.sources, self.origin.lon, self.origin.lat, self.mpp, far_map=False)
        if key in self.unavailable:
            self.fallback_from = key
            key = self._replacement(key)
        elif key == self.fallback_from:
            self.fallback_from = ''
        if self.source != key:
            self.failures.clear()
        self.source = key
        if key == tiles.NONE and not self.fallback_from:
            self.loaded.clear()
        self._wanted()

    def _replacement(self, failed):
        choices = tiles.fallbacks(self.sources, failed, self.origin.lon, self.origin.lat, self.mpp < 20)
        return next((key for key in choices if key not in self.unavailable), tiles.NONE)

    def _wanted(self):
        source = self.sources.get(self.source)
        if source is None or self.equal_earth:
            self.wanted = self.around = self.backdrop = set()
            self.under = {}
            return
        w, s, e, n = self.bounds
        # Not past the imagery's own detail (R516): further the server only enlarges the same pixels, the plan does
        # it as well, and the area kept for the plan without network stops there.
        view_zoom = tiles.zoom_for(self.mpp / self.dpr, self.origin.lat, source.last_zoom)
        z = max(source.min_zoom, view_zoom)
        far = view_zoom < source.min_zoom       # R539: coarser than the source has: its nearest level, near the site
        self.wanted = self._cover(self.bounds, z, limit=FAR_PHOTO_TILES if far else 400)
        # Around: half a view further on each side at this zoom, and the zoom above over the view (one step out):
        # a pan or a zoom out finds them in memory. Zooming in asks four times the tiles: not fetched in advance.
        dx, dy = (e - w) / 2, (n - s) / 2
        around = set() if far else self._cover((w - dx, s - dy, e + dx, n + dy), z)
        if around and z - 1 >= source.min_zoom:
            around |= {(key, z - 1, x // 2, y // 2) for key, _z, x, y in around}
        self.around = around - self.wanted
        # R540: the backdrop, asked before the view's own tiles (a few, and they cover the bands of a pan or a zoom out)
        zb = max(source.min_zoom, z - BACKDROP_STEPS)
        rx, ry = (e - w) * BACKDROP_REACH, (n - s) * BACKDROP_REACH
        self.backdrop = self._cover((w - rx, s - ry, e + rx, n + ry), zb) if zb < z else set()
        street = self.sources.get('osm')
        if far and street is not None and self.source != 'osm':
            # R539: the street map where the orthophoto does not reach, under it
            zs = max(street.min_zoom, min(street.last_zoom, view_zoom))
            self.backdrop = self._cover((w - rx, s - ry, e + rx, n + ry), zs, key='osm')
        self.failures.intersection_update(self.wanted)
        self._prune()

    def _cover(self, bounds, z, *, key=None, limit=400):
        w, s, e, n = bounds
        corners = [self.origin.to_lonlat(x, y) for x, y in ((w, s), (w, n), (e, s), (e, n))]
        # At the date line take the short longitude span, not almost the entire world.
        longitude = [self.origin.lon + ((lon - self.origin.lon + 180) % 360 - 180) for lon, _lat in corners]
        south, north = min(lat for _lon, lat in corners), max(lat for _lon, lat in corners)
        west, east = min(longitude), max(longitude)
        boxes = [(west, east)]
        if west < -180:
            boxes = [(west + 360, 180), (-180, east)]
        elif east > 180:
            boxes = [(west, 180), (-180, east - 360)]
        return {(key or self.source, z, x, y) for left, right in boxes
                for x, y in tiles.tiles_for(left, south, right, north, z, limit)
                if tiles.tile_in_hemisphere(self.origin, z, x, y)}

    def _prune(self):
        if self.wanted and self.wanted.issubset(self.loaded):
            self.loaded = {tile: url for tile, url in self.loaded.items() if tile in self.wanted}
        # the old backdrop stays under the view until the new one is whole
        if self.backdrop and self.backdrop.issubset(self.under):
            self.under = {tile: url for tile, url in self.under.items() if tile in self.backdrop}

    def ready(self, tile, url):
        if tile in self.backdrop:
            self.under[tile] = url
            self._prune()
        if tile not in self.wanted:
            return tile in self.backdrop
        self.loaded[tile] = url
        self.failures.discard(tile)
        self._prune()
        return True

    def failed(self, tile, now=None):
        if tile not in self.wanted:
            return False
        self.failures.add(tile)
        if len(self.failures) < FAILOVER_THRESHOLD:
            return False
        # R539: a source whose other tiles of the view come is not down: the tiles it refuses (the national
        # orthophoto keeps the error of some addresses) are stood in for by the coarser ones (R540), and the whole
        # plan no longer leaves the orthophoto for a street map for three minutes because of three of them
        if any(t[0] == self.source for t in self.loaded if t in self.wanted):
            return False
        self.unavailable[self.source] = time.monotonic() if now is None else now
        self.fallback_from = self.source
        self.source = self._replacement(self.source)
        self.failures.clear()
        self._wanted()
        return True

    def retry(self):
        self.unavailable.clear()
        self.fallback_from = ''
        self.failures.clear()
        self.choose()

    @property
    def attribution(self):
        if self.equal_earth or (self.mpp >= 250 and not self.loaded):
            return 'Natural Earth'
        # During replacement every still visible mosaic retains its legal credit.
        keys = list(dict.fromkeys([tile[0] for tile in self.loaded] + [tile[0] for tile in self.under]
                                  + [self.source]))
        return ' | '.join(self.sources[key].credit() for key in keys if key in self.sources)

    @property
    def fallback_message(self):
        if not self.fallback_from:
            return ''
        old, new = self.sources.get(self.fallback_from), self.sources.get(self.source)
        return _('{failed} is not reachable: using {replacement}.').format(
            failed=tiles.display_name(old) if old else self.fallback_from,
            replacement=tiles.display_name(new) if new else _('No background'))

    @property
    def veil_visible(self):
        return self.source != tiles.NONE and self.veil > 0 and not self.equal_earth

    def world(self):
        return world_geometry(self.origin, self.equal_earth)

    def stand_ins(self):
        """R540: for each tile of the view still on its way, the nearest coarser tile the memory or the plan already
        has, drawn enlarged under the sharper ones until it comes."""
        found, have = {}, dict(self.under)
        have.update(self.loaded)
        for key, z, x, y in self.wanted - self.loaded.keys():
            for k in range(1, ANCESTOR_STEPS + 1):
                parent = (key, z - k, x >> k, y >> k)
                if parent in found or parent in have:
                    break
                url = self.memory(parent) if self.memory is not None else None
                if url is not None:
                    found[parent] = url
                    break
        return found

    def records(self):
        # coarse first: a sharper tile is drawn over a coarser one (the delegate's z is its zoom)
        under = sorted(self.under.items(), key=lambda item: item[0][1])
        filling = sorted(self.stand_ins().items(), key=lambda item: item[0][1]) if self.wanted else []
        old = [(tile, url) for tile, url in self.loaded.items() if tile not in self.wanted]
        current = [(tile, url) for tile, url in self.loaded.items() if tile in self.wanted]
        seen, out = set(), []
        for tile, url in under + filling + old + current:
            if tile not in seen:
                seen.add(tile)
                out.extend(tile_records(self.origin, tile, url))
        return out
