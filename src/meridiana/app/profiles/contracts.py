"""Profile-specific app material, independent of the window."""
from typing import Protocol

class AppProfile(Protocol):
    id: str
    def report_chapters(self, project) -> dict: ...
    def report_fragment(self, key: str, ctx) -> list: ...
    def help_texts(self) -> dict: ...
    def assistant_system(self, name: str, lang: str) -> str: ...
    def assistant_passages(self) -> tuple[dict, ...]: ...
    def assistant_tool_specs(self) -> list[dict]: ...
    def catalog_context(self, records: dict) -> dict: ...
