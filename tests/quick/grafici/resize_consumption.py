"""Native D3D11 consumption border gestures on the actual calculated workbench."""
import argparse
import cProfile
import json
import pickle
import sys
import tempfile
import time
from collections import Counter
from pathlib import Path

from PySide6.QtCore import QPointF, QTimer, Qt, QCoreApplication, QEvent
from meridiana.quick.app import QuickWindow, create_app
from quick.gestures import drag, item, point, pump, wait_for


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('fixture', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--profile', action='store_true')
    parser.add_argument('--one', action='store_true')
    parser.add_argument('--trace-text', action='store_true')
    args = parser.parse_args()
    if args.output.exists():
        raise FileExistsError(args.output)
    with args.fixture.open('rb') as file:
        fixture = pickle.load(file)  # Locally generated by calculated_rho.
    app = create_app()
    with tempfile.TemporaryDirectory() as temporary:
        host = QuickWindow(fixture['project'], Path(temporary), real_views=True)
        win, bridge = host.window, host.bridge
        try:
            bridge.accept_layout(bridge.session.generation, fixture['results'], fixture['keys'])
            bridge._finished(bridge.session.generation, fixture['energy'], [], {})
            win.setFlags(Qt.WindowType.Window | Qt.WindowType.FramelessWindowHint)
            win.resize(1600, 960)
            win.show()
            host.shell.trigger('phase_consumption')
            result = host.parts.controllers['results']
            wait_for(lambda: not result.busy and bool(result.consumption['tiles'][0]['value']), 60)
            pump(1800)
            rows = []
            measures = Counter()
            def trace(frame, event, _arg):
                if event == 'call' and frame.f_code.co_name == 'measureText':
                    measures[frame.f_locals.get('text', '')] += 1
            gaps, last = [], [time.perf_counter()]
            def beat():
                now = time.perf_counter()
                gaps.append((now-last[0])*1000)
                last[0] = now
            timer = QTimer()
            timer.setInterval(2)
            timer.timeout.connect(beat)
            for size in (((1600, 960),) if args.one else ((1600, 960), (1366, 900), (1920, 1080))):
                win.resize(*size)
                pump(800)
                for name, delta in (('rightResizeHandle', QPointF(-140, 0)), ('bottomResizeHandle', QPointF(0, -80))):
                    if args.one and name != 'rightResizeHandle':
                        continue
                    handle = item(win, name)
                    start = point(handle)
                    assert handle.isVisible(), name
                    pending, visible_plots = [win.contentItem()], []
                    while pending:
                        candidate = pending.pop()
                        pending.extend(candidate.childItems())
                        if candidate.objectName() == 'plotArea' and candidate.isVisible():
                            visible_plots.append(candidate)
                    assert visible_plots, 'The consumption chart must be visible during the gesture'
                    plot = visible_plots[0]
                    before = [plot.width(), plot.height()]
                    gaps.clear()
                    last[0] = time.perf_counter()
                    timer.start()
                    profile = cProfile.Profile()
                    if args.profile:
                        profile.enable()
                    elif args.trace_text:
                        sys.setprofile(trace)
                    drag(app, win, start, start+delta, steps=120, pause=8)
                    middle = point(handle)
                    during = [plot.width(), plot.height()]
                    drag(app, win, point(handle), start, steps=120, pause=8)
                    timer.stop()
                    moved = abs(middle.x()-start.x()) if delta.x() else abs(middle.y()-start.y())
                    assert moved > 50, (name, start, middle)
                    if delta.x():
                        assert abs(before[0]-during[0]) > 50, (before, during)
                    if args.trace_text:
                        sys.setprofile(None)
                    if args.profile:
                        profile.disable()
                        profile.dump_stats(str(args.output.with_suffix('.prof')))
                    rows.append(dict(size=list(size), handle=name, samples=len(gaps),
                                     worst_ms=max(gaps, default=0), over30=[v for v in gaps if v > 30],
                                     handle_moved=moved, plot_before=before, plot_during=during))
                    print({k:v for k,v in rows[-1].items() if k != 'over30'}, 'stalls:', len(rows[-1]['over30']), flush=True)
            payload = dict(platform=app.platformName(), graphics=str(win.rendererInterface().graphicsApi()),
                           monitor_presentation=False, rows=rows, warnings=host.warnings,
                           hours=len(fixture['energy']['sim'].hourly), basis=result.consumption.get('basis'))
            payload['text_measurements'] = measures.most_common()
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding='utf8')
        finally:
            host.close()
            QCoreApplication.sendPostedEvents(None, QEvent.Type.DeferredDelete)
            app.processEvents()


if __name__ == '__main__':
    main()
